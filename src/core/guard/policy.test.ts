import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { RawPageText, StoredPostingText, VisibleText } from '../types/text';
import { POLICY_PATTERNS, policyHits, policyKindOf } from './policy';

const visible = (text: string) => text as VisibleText;

describe('the policy patterns (§7.10)', () => {
  it('are the design’s seven, in its order, then the Phase 7a review’s, each with its own id', () => {
    const design = readFileSync(new URL('../../../docs/design/core.md', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
    const block = /^```ts\n([\s\S]*?)^```$/m.exec(design.slice(design.indexOf('### 7.10')));
    expect(block).not.toBeNull();
    const source = readFileSync(new URL('./policy.ts', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
    const regexes = [...block![1]!.matchAll(/re: (new RegExp\(String\.raw`.*?`, 'i'\)|\/.*\/i) \}/g)].map((m) => m[1]!);
    expect(regexes).toHaveLength(7);
    for (const re of regexes) expect(source, re).toContain(re);
    // Every fragment the patterns share, as the design writes it.
    const fragments = [...block![1]!.matchAll(/^const [A-Z_]+ = .*$/gm)].map((m) => m[0]);
    expect(fragments.map((line) => /^const ([A-Z_]+)/.exec(line)![1])).toEqual(['AIX', 'OPENS', 'APPLICANT',
      'EMPLOYER_ACTION', 'GAP', 'VERDICT']);
    for (const line of fragments) expect(source, line).toContain(line);
    expect(new Set(POLICY_PATTERNS.map((pattern) => pattern.id)).size).toBe(8);
    expect(POLICY_PATTERNS.at(-1)).toMatchObject({ id: 'own-words', kind: 'ai-prohibited' });
  });

  it.each<[string, string]>([
    ['Please do not use AI tools to complete this application.', 'do-not-use-ai'],
    ['Do not use ChatGPT to answer these questions.', 'do-not-use-ai'],
    ['You don’t use any generative AI here.', 'do-not-use-ai'],
    ['AI-generated applications will be rejected.', 'ai-generated-rejected'],
    ['Applications written using AI will be disqualified.', 'generated-by-ai-rejected'],
    ['The use of AI is strictly prohibited.', 'ai-is-prohibited'],
    ['Complete the questions without the use of AI.', 'without-ai'],
    ['No AI, please.', 'no-ai'],
    ['Automated applications will be rejected.', 'automated-applications-rejected'],
    ['Please answer every question in your own words.', 'own-words'],
    ['We want to hear from you, so write it yourself.', 'own-words'],
    ['Complete the application yourself; we read every answer.', 'own-words'],
  ])('finds %j', (text, id) => {
    expect(policyHits(visible(text))).toContain(id);
  });

  it('leaves ordinary postings alone', () => {
    for (const text of ['We do not use AI to screen candidates.', 'No AI experience required.',
      'You will build AI tools for our customers.', 'We use AI to match jobs.', 'You will own the words on our website.',
      'Write tests yourself and review others.', '']) {
      expect(policyHits(visible(text)), text).toEqual([]);
    }
  });

  // CORE-5 and CORE-12 (Phase 2 review): the patterns missed many ways a posting forbids AI to the applicant, and they
  // read an employer's own non-use of AI as a prohibition. The two pull apart, so they are tested together: a
  // prohibition needs the applicant as its subject, an imperative, or the applicant's work as its object.
  it.each([
    'AI-generated applications will not be accepted.',
    'AI-generated applications will not be considered.',
    'Applications generated by AI will not be considered.',
    'The use of AI tools (e.g., ChatGPT) to complete this application is not permitted.',
    'Use of AI in this application is prohibited.',
    'Using AI to complete this application is not allowed.',
    'Please refrain from using AI tools.',
    'We do not accept AI-generated applications.',
    'Candidates are not permitted to use AI.',
    'AI tools may not be used.',
    'You must not use ChatGPT or other AI tools.',
    'Applicants should not use generative AI to write their answers.',
    'Do not use tools like ChatGPT when you answer.',
    'Thank you for applying. Do not use AI for the written questions.',
    'Please complete this application without the use of AI.',
    'Your answers must be written without the help of AI.',
    'Responses written with AI will not be considered.',
    'Candidates must refrain from using AI tools.',
    'We do not allow candidates to use AI.',
    'Acme does not permit applicants to use generative AI when answering.',
  ])('finds the prohibition in %j', (text) => {
    expect(policyHits(visible(text)), text).not.toEqual([]);
  });

  it.each([
    'Our recruiters do not use AI to screen candidates.',
    'No AI is used to make hiring decisions.',
    'Hiring decisions are made without the use of AI.',
    'AI is not permitted to make final hiring decisions.',
    'Acme does not use AI to evaluate applications.',
    'We refrain from using AI in our hiring process.',
    'AI tools may not be used to make hiring decisions.',
    'Your application will be reviewed by people, without the use of AI.',
    'You may use AI tools to polish your resume.',
    'Our team does not use any AI when reviewing resumes.',
  ])('reads %j as the employer’s own practice, no prohibition', (text) => {
    expect(policyHits(visible(text)), text).toEqual([]);
  });

  it('reads TailorIT’s stored copy of the posting alike, and folds look-alike letters', () => {
    expect(policyHits('Do not use \u{0410}I tools to apply.' as StoredPostingText)).toEqual(['do-not-use-ai']);
  });

  it('reads the raw scan’s hidden passages alike, for detection only (S6)', () => {
    expect(policyHits('Show more: Do not use AI tools to apply.' as RawPageText)).toEqual(['do-not-use-ai']);
    expect(policyHits('We use AI to match jobs.' as RawPageText)).toEqual([]);
  });

  it('answers ids in pattern order, each once', () => {
    expect(policyHits(visible('No AI. Do not use AI. No AI at all.'))).toEqual(['do-not-use-ai', 'no-ai']);
  });

  it('gives each id its kind', () => {
    expect(policyKindOf('automated-applications-rejected')).toBe('automation-prohibited');
    expect(policyKindOf('no-ai')).toBe('ai-prohibited');
    expect(policyKindOf('unknown')).toBeNull();
  });
});
